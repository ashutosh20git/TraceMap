"""Import a pinned SigmaHQ release into config/rules/sigma.yaml and write an import report.

    python scripts/sigma_import.py third_party/sigma/sigma_all_rules-r2026-07-01.zip r2026-07-01
"""
import collections
import json
import sys
import zipfile

import yaml

sys.path.insert(0, ".")
from trustgate.detection.sigma import Skip, convert  # noqa: E402


def main(zpath, release, out="config/rules/sigma.yaml", report="third_party/sigma/import_report.json"):
    z = zipfile.ZipFile(zpath)
    rules, skipped, seen = [], collections.Counter(), set()
    examples = {}
    for name in sorted(n for n in z.namelist() if n.endswith((".yml", ".yaml"))):
        try:
            docs = [d for d in yaml.safe_load_all(z.read(name).decode("utf-8")) if d]
            if len(docs) != 1:
                raise Skip("multi-document rule")
            r = convert(docs[0], name, release)
            if r["id"] in seen:
                raise Skip("duplicate id")
            seen.add(r["id"])
            rules.append(r)
        except Skip as e:
            reason = str(e).split(" near ")[0]
            key = reason if len(reason) < 60 else reason[:60]
            skipped[key] += 1
            examples.setdefault(key, name)
        except Exception as e:  # malformed YAML or validation failure
            key = f"invalid: {type(e).__name__}"
            skipped[key] += 1
            examples.setdefault(key, name)
    header = (f"# Generated by scripts/sigma_import.py from SigmaHQ {release} ({zpath.split('/')[-1]}).\n"
              f"# Sigma rules: Detection Rule License (DRL) 1.1 - https://github.com/SigmaHQ/Detection-Rule-License\n"
              f"# Each rule keeps its Sigma id, author and source path. Do not edit by hand; re-run the importer.\n")
    with open(out, "w", encoding="utf-8") as f:
        f.write(header)
        yaml.safe_dump({"attack_version": "ATT&CK (Sigma tags)", "rules": rules}, f, sort_keys=False, allow_unicode=True, width=200)
    by_tactic = collections.Counter(t for r in rules for t in (r["tactics"] or ["unmapped"]))
    rep = {"release": release, "files": len(z.namelist()), "imported": len(rules), "skipped": sum(skipped.values()),
           "skip_reasons": dict(skipped.most_common()), "skip_examples": examples,
           "imported_by_level": dict(collections.Counter(r["severity"] for r in rules)),
           "imported_by_tactic": dict(by_tactic.most_common()),
           "imported_by_product": dict(collections.Counter(r["source"]["logsource"].get("product", "-") for r in rules).most_common())}
    with open(report, "w", encoding="utf-8") as f:
        json.dump(rep, f, indent=1)
    print(json.dumps({k: rep[k] for k in ("imported", "skipped", "imported_by_level")}, indent=1))
    print("top skip reasons:", dict(skipped.most_common(8)))


if __name__ == "__main__":
    main(*sys.argv[1:3])
